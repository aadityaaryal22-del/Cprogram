//Write a program to demonstrate all relational operators.
#include <stdio.h>
#include <conio.h>

int main()
{
    int a = 10, b = 20;

    printf("a > b  = %d\n", a > b);
    printf("a < b  = %d\n", a < b);
    printf("a >= b = %d\n", a >= b);
    printf("a <= b = %d\n", a <= b);
    printf("a == b = %d\n", a == b);
    printf("a != b = %d\n", a != b);

    getch();
    return 0;
}